    EfficientTurbo,     // Turbo eficiente
    DoubleDash,         // Dash doble
    ReinforcedPlates,   // Placas reforzadas (más armadura)
    BubbleShield,       // Escudo de burbuja
    WaterRepair,        // Reparación acuática
    ExtendedMag,        // Cargador ampliado
    PickupMagnet,       // Imán de cápsulas
    Sonar               // Sonar (marca aves que cazan y peces atrapados)
}
